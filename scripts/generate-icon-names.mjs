/**
 * Regenerates `src/shared/ui/icon-names.ts` from `design-system/tevi-icons.svg`.
 *
 * The sprite ships one bare `<symbol id="name">` per glyph (the default weight)
 * plus `name--{regular,filled,light,duotone,duotone-line}` — but only for the
 * glyphs Figma actually drew in that weight (a handful lack one or more).
 * So each weight gets its own name union and `Icon` discriminates on it, making
 * a missing weight a type error instead of an `<svg>` that renders nothing.
 *
 *   node scripts/generate-icon-names.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs'

const WEIGHTS = [
    ['regular', 'Regular'],
    ['filled', 'Filled'],
    ['light', 'Light'],
    ['duotone', 'Duotone'],
    ['duotone-line', 'DuotoneLine'],
]

/**
 * The Figma export, and nothing else: a legal `<Icon name>` is a glyph the library has — what
 * `/dev/icons` shows. (An overlay of upstream Zappicon glyphs used to be merged in here; it was
 * removed so that the type itself refuses any icon design did not put in the library.)
 */
const sprite = readFileSync('design-system/tevi-icons.svg', 'utf8')
const ids = new Set([...sprite.matchAll(/<symbol id="([^"]+)"/g)].map(m => m[1]))
const names = [...ids].filter(id => !id.includes('--')).sort()

if (names.length === 0) throw new Error('no glyphs found in design-system/tevi-icons.svg')

const namesFor = weight => names.filter(n => ids.has(`${n}--${weight}`))
const union = list => list.map(n => `    | '${n}'`).join('\n')

const blocks = WEIGHTS.map(([weight, pascal]) => {
    const available = namesFor(weight)
    return `/** ${available.length} glyphs are drawn in the \`${weight}\` weight. */
export type TeviIconName${pascal} =
${union(available)}
`
})

writeFileSync(
    'src/shared/ui/icon-names.ts',
    `// Generated by scripts/generate-icon-names.mjs — do not edit by hand.
// ${names.length} glyphs from the Tevi design system sprite (design-system/tevi-icons.svg).

/** Every glyph in the sprite, at its default weight. */
export type TeviIconName =
${union(names)}

${blocks.join('\n')}`,
)

console.log(
    `wrote src/shared/ui/icon-names.ts — ${names.length} glyphs, ` +
        WEIGHTS.map(([w]) => `${w}:${namesFor(w).length}`).join(' '),
)
